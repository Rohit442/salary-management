CREATE TABLE hr_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(200) NOT NULL,
    role VARCHAR(20) NOT NULL,
    enabled BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT uq_hr_user_email UNIQUE (work_email),
    CONSTRAINT ck_hr_user_email CHECK (work_email = LOWER(TRIM(work_email)) AND CHAR_LENGTH(work_email) > 0),
    CONSTRAINT ck_hr_user_display_name CHECK (CHAR_LENGTH(TRIM(display_name)) > 0),
    CONSTRAINT ck_hr_user_role CHECK (role = 'HR')
);

--changeset salary-management:005-create-currency
CREATE TABLE currency (
    code CHAR(3) PRIMARY KEY,
    fraction_digits SMALLINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT ck_currency_code CHECK (REGEXP_LIKE(code, '^[A-Z]{3}$')),
    CONSTRAINT ck_currency_precision CHECK (fraction_digits BETWEEN 0 AND 4),
    CONSTRAINT ck_currency_name CHECK (CHAR_LENGTH(TRIM(name)) > 0)
);
