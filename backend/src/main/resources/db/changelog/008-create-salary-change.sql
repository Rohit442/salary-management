--changeset salary-management:008-create-salary-change
CREATE TABLE salary_change (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_fk BIGINT NOT NULL,
    actor_fk BIGINT NOT NULL,
    actor_display_name VARCHAR(200) NOT NULL,
    previous_amount DECIMAL(19,4) NOT NULL,
    new_amount DECIMAL(19,4) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    effective_date DATE NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resulting_version BIGINT NOT NULL,
    request_id VARCHAR(36) NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    CONSTRAINT fk_salary_change_employee_currency FOREIGN KEY (employee_fk, currency_code) REFERENCES employee(id, currency_code),
    CONSTRAINT fk_salary_change_actor FOREIGN KEY (actor_fk) REFERENCES hr_user(id),
    CONSTRAINT fk_salary_change_currency FOREIGN KEY (currency_code) REFERENCES currency(code),
    CONSTRAINT uq_salary_change_actor_request UNIQUE (actor_fk, request_id),
    CONSTRAINT uq_salary_change_employee_version UNIQUE (employee_fk, resulting_version),
    CONSTRAINT uq_salary_change_employee_effective UNIQUE (employee_fk, effective_date),
    CONSTRAINT ck_salary_change_amounts CHECK (previous_amount > 0 AND new_amount > 0 AND previous_amount <> new_amount),
    CONSTRAINT ck_salary_change_version CHECK (resulting_version BETWEEN 1 AND 9007199254740991),
    CONSTRAINT ck_salary_change_actor_name CHECK (CHAR_LENGTH(TRIM(actor_display_name)) > 0),
    CONSTRAINT ck_salary_change_reason CHECK (CHAR_LENGTH(TRIM(reason)) > 0),
    CONSTRAINT ck_salary_change_request_id CHECK (REGEXP_LIKE(request_id, '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')),
    CONSTRAINT ck_salary_change_fingerprint CHECK (REGEXP_LIKE(request_fingerprint, '^[0-9a-f]{64}$'))
);

--changeset salary-management:008-index-salary-history
CREATE INDEX ix_salary_change_history ON salary_change(employee_fk, changed_at DESC, id DESC);
